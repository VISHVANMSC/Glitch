export function normalizeCollegeName(name: string): string {
  if (!name) return '';
  return name
    .toLowerCase()
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/[^a-z0-9]/g, '');
}

export function searchColleges(query: string, collegesList: string[] = INDIAN_COLLEGES): string[] {
  if (!query || query.trim() === '') return collegesList;
  const q = query.toLowerCase().trim();
  const qNorm = normalizeCollegeName(query);

  return collegesList.filter((c) => {
    const cLower = c.toLowerCase();
    const cNorm = normalizeCollegeName(c);
    return cLower.includes(q) || cNorm.includes(qNorm);
  });
}

export function findExistingCollegeMatch(query: string, collegesList: string[] = INDIAN_COLLEGES): string | null {
  if (!query || !query.trim()) return null;
  const qNorm = normalizeCollegeName(query);
  return collegesList.find((c) => normalizeCollegeName(c) === qNorm) || null;
}

export function addCustomCollege(newCollegeName: string): string {
  const cleaned = newCollegeName.trim().replace(/\s+/g, ' ');
  const match = findExistingCollegeMatch(cleaned, INDIAN_COLLEGES);
  if (match) {
    return match; // Return canonical existing college if duplicate match found
  }
  if (!INDIAN_COLLEGES.includes(cleaned)) {
    INDIAN_COLLEGES.unshift(cleaned);
  }
  return cleaned;
}
